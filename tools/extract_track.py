"""Extract road / island polygons for the Tobu (Numazu) driving test course
from a top-down satellite screenshot.

Usage:  python3 tools/extract_track.py path/to/satellite.webp src/trackData.js

The output coordinates are in *satellite pixels* of the 2000x1414 reference
screenshot (1 px ~= 0.115 m). src/geo.js converts them to metres.
Requires: pillow numpy scipy scikit-image
"""
import sys, json
from PIL import Image
import numpy as np
from scipy import ndimage as ndi
from skimage import measure, morphology

src = sys.argv[1] if len(sys.argv) > 1 else 'satellite.webp'
out = sys.argv[2] if len(sys.argv) > 2 else 'src/trackData.js'

im = np.asarray(Image.open(src).convert('RGB')).astype(float)
r, g, b = im[..., 0], im[..., 1], im[..., 2]
mx = im.max(-1); mn = im.min(-1)

# asphalt = dark, unsaturated grey. Painted lines (white) are road as well.
road = ((mx - mn) < 28) & (mx < 170)
# map labels (blue boxes) and sign icons (red) -> inpaint from neighbours
lab_mask = ((b - r) > 35) | ((r - g) > 70)
lab_mask = morphology.dilation(lab_mask, morphology.disk(7))
white = (mn > 170) & ~lab_mask
road = road | white
_, ind = ndi.distance_transform_edt(lab_mask, return_indices=True)
road = road[ind[0], ind[1]]

# region of interest = the course itself
roi = np.zeros_like(road)
roi[0:957, 272:1740] = True
road &= roi
# departure lane under the canopy (hidden by the roof in the satellite view)
road[955:1001, 440:1142] = True
# level crossing plates (reddish, missed by the colour test)
road[18:96, 866:910] = True
# IN/OUT road continues south a little
road[955:1001, 360:416] = True

road = morphology.closing(road, morphology.disk(3))
road = morphology.remove_small_objects(road, max_size=400)
lab, n = ndi.label(road)
road = lab == lab[460, 700]
holes = ~road
hl, hn = ndi.label(holes)
sizes = ndi.sum(holes, hl, range(1, hn + 1))
for i, s in enumerate(sizes):
    if s < 900:
        road[hl == i + 1] = True
road = morphology.opening(road, morphology.disk(2))
# thin raised divider between main road and the departure lane
road[952:960, 640:1062] = False

f = 4
sm = ndi.gaussian_filter(road.astype(float), 2.2)
up = ndi.zoom(sm, f, order=1)
polys = []
for c in measure.find_contours(up, 0.5):
    c = measure.approximate_polygon(c, 0.6)
    pts = [[round(p[1] / f, 1), round(p[0] / f, 1)] for p in c]
    if len(pts) < 4:
        continue
    a = 0
    for i in range(len(pts)):
        x1, y1 = pts[i]; x2, y2 = pts[(i + 1) % len(pts)]
        a += x1 * y2 - x2 * y1
    if abs(a) / 2 < 150:
        continue
    polys.append((a / 2, pts))
polys.sort(key=lambda p: -abs(p[0]))
outer = polys[0][1]
islands = [p[1] for p in polys[1:]]

def flat(pts):
    return [v for p in pts for v in p]

with open(out, 'w') as fh:
    fh.write('// Generated by tools/extract_track.py - do not edit by hand.\n')
    fh.write('// Coordinates are satellite-image pixels (see src/geo.js).\n')
    fh.write('export const ROAD_OUTER = ' + json.dumps(flat(outer)) + ';\n')
    fh.write('export const ISLANDS = [\n')
    for isl in islands:
        fh.write('  ' + json.dumps(flat(isl)) + ',\n')
    fh.write('];\n')
print('outer pts', len(outer), 'islands', len(islands))
